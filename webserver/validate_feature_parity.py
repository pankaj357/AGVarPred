"""Compare live AGVarPred features and scores with a reference feature matrix.

Use a small reference matrix generated by the established research pipeline for
the same variants. This command makes real AlphaGenome API calls; run it only
on a trusted machine with the required credentials and gnomAD VCF configured.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from AGVarPred import AGVarPredPredictor
from agvarpred_core.utils import parse_variant_id
from webserver.prediction_service import (
    LivePredictionService,
    alpha_feature_names,
    apply_training_missing_annotation_defaults,
    missing_model_feature_columns,
)


def _json_value(value: Any) -> Any:
    """Convert pandas/numpy values into JSON-safe builtins."""
    if value is None or pd.isna(value):
        return None
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, (np.bool_, bool)):
        return bool(value)
    return str(value)


def compare_selected_features(
    reference: pd.DataFrame,
    generated: pd.DataFrame,
    feature_names: list[str],
    tolerance: float,
) -> dict[str, Any]:
    """Compare selected numeric model features for common variant IDs."""
    missing_reference_columns = [
        name for name in feature_names if name not in reference.columns
    ]
    missing_generated_columns = [
        name for name in feature_names if name not in generated.columns
    ]
    if missing_reference_columns or missing_generated_columns:
        raise ValueError(
            "Selected feature columns are missing: "
            f"reference={missing_reference_columns[:8]}, "
            f"generated={missing_generated_columns[:8]}"
        )

    common_ids = [
        variant_id for variant_id in reference.index.astype(str)
        if variant_id in generated.index
    ]
    common_ids = list(dict.fromkeys(common_ids))
    if not common_ids:
        raise ValueError("Reference and generated matrices have no common variant IDs.")

    ref_raw = reference.loc[common_ids, feature_names]
    gen_raw = generated.loc[common_ids, feature_names]
    ref_num = ref_raw.apply(pd.to_numeric, errors="coerce")
    gen_num = gen_raw.apply(pd.to_numeric, errors="coerce")

    # Invalid non-numeric values must not become indistinguishable from true NaNs.
    ref_invalid = ref_raw.notna() & ref_num.isna()
    gen_invalid = gen_raw.notna() & gen_num.isna()
    ref_arr = ref_num.to_numpy(dtype=float)
    gen_arr = gen_num.to_numpy(dtype=float)

    close = np.isclose(ref_arr, gen_arr, rtol=0.0, atol=tolerance, equal_nan=True)
    close &= ~ref_invalid.to_numpy()
    close &= ~gen_invalid.to_numpy()

    mismatches: list[dict[str, Any]] = []
    mismatch_positions = np.argwhere(~close)
    for row_idx, col_idx in mismatch_positions[:30]:
        mismatches.append(
            {
                "variant_id": common_ids[int(row_idx)],
                "feature": feature_names[int(col_idx)],
                "reference": _json_value(ref_raw.iloc[int(row_idx), int(col_idx)]),
                "generated": _json_value(gen_raw.iloc[int(row_idx), int(col_idx)]),
            }
        )

    finite_pairs = np.isfinite(ref_arr) & np.isfinite(gen_arr)
    if finite_pairs.any():
        max_abs_diff: float | None = float(
            np.max(np.abs(ref_arr[finite_pairs] - gen_arr[finite_pairs]))
        )
    else:
        max_abs_diff = None

    total = int(close.size)
    matching = int(close.sum())
    return {
        "common_variants": len(common_ids),
        "features_compared": len(feature_names),
        "feature_values_compared": total,
        "feature_values_within_tolerance": matching,
        "feature_mismatches": total - matching,
        "feature_match_rate": float(matching / total) if total else 0.0,
        "feature_tolerance": tolerance,
        "max_absolute_difference_finite_pairs": max_abs_diff,
        "mismatch_examples": mismatches,
    }


def _load_reference(path: Path, feature_names: list[str]) -> pd.DataFrame:
    """Read a research feature matrix and normalize variant IDs into the index."""
    reference = pd.read_parquet(path)
    if "variant_id" in reference.columns:
        reference["variant_id"] = reference["variant_id"].astype(str)
        reference = reference.set_index("variant_id", drop=False)
    else:
        reference.index = reference.index.astype(str)
        reference.index.name = "variant_id"

    missing = [name for name in feature_names if name not in reference.columns]
    if missing:
        raise ValueError(
            "Reference file does not contain all selected model features. "
            f"Missing (first 12): {missing[:12]}"
        )
    if reference.index.has_duplicates:
        reference = reference.loc[~reference.index.duplicated(keep="first")]
    return reference


def run_parity_check(
    reference_path: Path,
    max_variants: int = 5,
    feature_tolerance: float = 1e-6,
    probability_tolerance: float = 1e-6,
) -> dict[str, Any]:
    """Run live feature generation against a frozen research reference matrix."""
    if max_variants < 1:
        raise ValueError("--max-variants must be at least 1")

    predictor = AGVarPredPredictor(model_name="model_full", af_source_name="webserver")
    selected = list(predictor.selected_features)
    reference = _load_reference(reference_path, selected)

    all_ids = reference.index.astype(str).tolist()
    if not all_ids:
        raise ValueError("The reference matrix contains no variants.")

    # Sample across the file deterministically so the initial check is small.
    sample_n = min(max_variants, len(all_ids))
    sample_positions = np.linspace(0, len(all_ids) - 1, num=sample_n, dtype=int)
    variant_ids = list(dict.fromkeys(all_ids[int(i)] for i in sample_positions))

    variant_rows = []
    for variant_id in variant_ids:
        chrom, pos, ref, alt = parse_variant_id(variant_id)
        ref_row = reference.loc[variant_id]
        gene_value = ""
        for gene_col in ("gene", "GeneSymbol"):
            if gene_col in reference.columns:
                value = ref_row[gene_col]
                gene_value = "" if pd.isna(value) else str(value)
                break
        variant_rows.append(
            {
                "chrom": chrom,
                "pos": pos,
                "ref": ref,
                "alt": alt,
                "gene": gene_value,
                "variant_id": variant_id,
            }
        )
    variants_df = pd.DataFrame(variant_rows)

    # Uses the same configuration checks and feature generator as the API service.
    service = LivePredictionService(predictor)
    generated = service.feature_generator.from_variants(variants_df)

    alpha_names = alpha_feature_names(selected)
    missing_alpha = [name for name in alpha_names if name not in generated.columns]
    if missing_alpha:
        raise RuntimeError(
            "Live AlphaGenome output is missing selected model tracks; "
            f"first missing tracks: {missing_alpha[:12]}"
        )
    generated = apply_training_missing_annotation_defaults(generated, selected)
    missing_selected = missing_model_feature_columns(generated, selected)
    if missing_selected:
        raise RuntimeError(
            "Live feature matrix is missing selected features after preprocessing; "
            f"first missing features: {missing_selected[:12]}"
        )

    generated_ids = set(generated.index.astype(str))
    missing_ids = [variant_id for variant_id in variant_ids if variant_id not in generated_ids]
    generated_has_alpha = {
        variant_id: (
            variant_id in generated.index
            and generated.loc[variant_id, alpha_names].notna().any()
        )
        for variant_id in variant_ids
    }
    no_usable_alpha = [
        variant_id for variant_id, usable in generated_has_alpha.items() if not usable
    ]
    scorable_ids = [
        variant_id for variant_id in variant_ids
        if generated_has_alpha.get(variant_id, False)
    ]

    # Compare feature values and scores only for variants with live feature rows.
    reference_sample = reference.loc[scorable_ids, selected]
    generated_sample = generated.loc[scorable_ids]
    feature_report = (
        compare_selected_features(
            reference_sample, generated_sample, selected, feature_tolerance
        )
        if scorable_ids
        else {
            "common_variants": 0,
            "features_compared": len(selected),
            "feature_values_compared": 0,
            "feature_values_within_tolerance": 0,
            "feature_mismatches": None,
            "feature_match_rate": 0.0,
            "feature_tolerance": feature_tolerance,
            "max_absolute_difference_finite_pairs": None,
            "mismatch_examples": [],
        }
    )

    probability_report: dict[str, Any] = {
        "variants_compared": 0,
        "max_absolute_probability_difference": None,
        "all_classes_agree": False,
        "probability_tolerance": probability_tolerance,
    }
    if scorable_ids:
        ref_predictions = predictor.predict(reference_sample).set_index("variant_id")
        live_predictions = predictor.predict(generated_sample).set_index("variant_id")
        ref_probs = ref_predictions.loc[scorable_ids, "probability"].to_numpy(dtype=float)
        live_probs = live_predictions.loc[scorable_ids, "probability"].to_numpy(dtype=float)
        prob_diffs = np.abs(ref_probs - live_probs)
        class_agreement = (
            ref_predictions.loc[scorable_ids, "predicted_class"].to_numpy()
            == live_predictions.loc[scorable_ids, "predicted_class"].to_numpy()
        )
        probability_report = {
            "variants_compared": len(scorable_ids),
            "max_absolute_probability_difference": float(np.max(prob_diffs)),
            "all_probability_differences_within_tolerance": bool(
                np.all(prob_diffs <= probability_tolerance)
            ),
            "all_classes_agree": bool(np.all(class_agreement)),
            "probability_tolerance": probability_tolerance,
            "probability_differences": {
                variant_id: float(diff)
                for variant_id, diff in zip(scorable_ids, prob_diffs)
            },
        }

    passed = (
        not missing_ids
        and not no_usable_alpha
        and feature_report["feature_mismatches"] == 0
        and probability_report.get("all_probability_differences_within_tolerance", False)
        and probability_report["all_classes_agree"]
    )
    return {
        "passed": bool(passed),
        "model_version": predictor.model_version,
        "alpha_features_expected": len(alpha_names),
        "selected_features_expected": len(selected),
        "reference_matrix": str(reference_path),
        "requested_variants": len(variant_ids),
        "missing_live_feature_rows": missing_ids,
        "variants_without_usable_alphagenome_scores": no_usable_alpha,
        "feature_comparison": feature_report,
        "prediction_comparison": probability_report,
        "note": (
            "This validates the sampled variants only. Passing does not replace "
            "broader benchmark validation or production monitoring."
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Compare live AGVarPred features/scores with a research reference matrix."
    )
    parser.add_argument(
        "--reference",
        type=Path,
        required=True,
        help="Parquet feature matrix from the established research pipeline.",
    )
    parser.add_argument(
        "--max-variants",
        type=int,
        default=5,
        help="Maximum number of deterministic reference variants to query (default: 5).",
    )
    parser.add_argument(
        "--feature-tolerance",
        type=float,
        default=1e-6,
        help="Absolute tolerance for selected-feature comparisons (default: 1e-6).",
    )
    parser.add_argument(
        "--probability-tolerance",
        type=float,
        default=1e-6,
        help="Absolute tolerance for calibrated probability comparisons (default: 1e-6).",
    )
    parser.add_argument("--output", type=Path, help="Optional path to save the JSON report.")
    args = parser.parse_args()

    report = run_parity_check(
        reference_path=args.reference,
        max_variants=args.max_variants,
        feature_tolerance=args.feature_tolerance,
        probability_tolerance=args.probability_tolerance,
    )
    rendered = json.dumps(report, indent=2, ensure_ascii=False)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered + "\n")
    print(rendered)
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
